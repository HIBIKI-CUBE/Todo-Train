#!/bin/sh
# Write $(DERIVED_FILE_DIR)/BuildInfo.swift for the calling target.
# Git が無い、またはリポジトリでないときは unknown を書いてビルドは続ける。
# sha と dirty が前回と同じなら builtAt もファイルも変えない。
set -u

if [ -z "${DERIVED_FILE_DIR:-}" ]; then
  echo "build-info: DERIVED_FILE_DIR is unset" >&2
  exit 1
fi

out="${DERIVED_FILE_DIR}/BuildInfo.swift"
mkdir -p "$(dirname "$out")"

sha="unknown"
branch="unknown"
dirty="false"
built_at="unknown"

if command -v git >/dev/null 2>&1 && [ -n "${SRCROOT:-}" ] \
  && git -C "$SRCROOT" rev-parse --is-inside-work-tree >/dev/null 2>&1
then
  head=$(git -C "$SRCROOT" rev-parse HEAD 2>/dev/null || true)
  name=$(git -C "$SRCROOT" rev-parse --abbrev-ref HEAD 2>/dev/null || true)
  if [ -n "$head" ] && [ -n "$name" ]; then
    sha=$(printf '%s' "$head" | cut -c1-7)
    branch=$name
    # 未追跡ファイルは数えない。追跡中の変更だけ dirty。
    status=$(git -C "$SRCROOT" status --porcelain --untracked-files=no 2>/dev/null || true)
    if [ -n "$status" ]; then
      dirty="true"
    fi
    built_at=$(TZ=Asia/Tokyo date +%Y-%m-%dT%H:%M:%S+09:00 2>/dev/null || echo unknown)
  fi
fi

if [ -f "$out" ]; then
  prev_sha=$(sed -n 's/.*static let sha = "\([^"]*\)".*/\1/p' "$out" | head -n 1)
  prev_dirty=$(sed -nE 's/.*static let dirty = (true|false).*/\1/p' "$out" | head -n 1)
  prev_built=$(sed -n 's/.*static let builtAt = "\([^"]*\)".*/\1/p' "$out" | head -n 1)
  if [ "$prev_sha" = "$sha" ] && [ "$prev_dirty" = "$dirty" ] && [ -n "$prev_built" ]; then
    built_at=$prev_built
  fi
fi

escape() {
  printf '%s' "$1" | sed 's/\\/\\\\/g; s/"/\\"/g'
}

sha_esc=$(escape "$sha")
branch_esc=$(escape "$branch")
built_esc=$(escape "$built_at")

tmp="${out}.tmp"
cat > "$tmp" <<EOF
// Generated by tools/build-info/generate.sh. Do not edit.
nonisolated enum BuildInfo {
    static let sha = "${sha_esc}"
    static let branch = "${branch_esc}"
    static let dirty = ${dirty}
    static let builtAt = "${built_esc}"
}
EOF

if [ -f "$out" ] && cmp -s "$tmp" "$out"; then
  rm -f "$tmp"
  exit 0
fi

mv "$tmp" "$out"
